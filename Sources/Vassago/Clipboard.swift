import AppKit
import ImageIO
import UniformTypeIdentifiers
import VassagoEngine

/// Watches the clipboard, records what is copied, and puts a clip back.
/// Everything that touches the clipboard or the disk runs on one background queue, never on the main thread.
final class Clipboard {
    /// What macOS lets Vassago do with the clipboard when nobody pressed Paste.
    enum Access {
        case allowed, neverAsked, notAllowed
    }

    /// Privacy & Security → Paste from Other Apps.
    static let settingsPane = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard")!

    /// macOS 15.4 and later ask the user before an app reads the clipboard on its own.
    static var access: Access {
        guard #available(macOS 15.4, *) else { return .allowed }
        switch NSPasteboard.general.accessBehavior {
        case .alwaysAllow: return .allowed
        case .default: return .neverAsked
        default: return .notAllowed
        }
    }

    /// Called on the main thread with the clips, newest first, whenever they change.
    var onChange: ([Clip]) -> Void = { _ in }

    private static let own = NSPasteboard.PasteboardType("com.quyennguyenvu.vassago.own")
    /// Marked secret or short-lived by the copying app, written by Vassago itself, or still on another device.
    private static let skipped: Set = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.apple.is-remote-clipboard", own.rawValue,
    ]
    private static let largest = 20_000_000

    private let queue = DispatchQueue(label: "com.quyennguyenvu.vassago.clipboard", qos: .utility)
    private let pasteboard = NSPasteboard.general
    private let store = Store()
    private var history = History()
    private var timer: DispatchSourceTimer?
    private var seen = 0
    private var recording = false

    /// Loads the saved clips and starts watching.
    func start() {
        queue.async { [self] in
            history = History(clips: store.load())
            publish()
            // What is already on the clipboard is not recorded.
            seen = pasteboard.changeCount
            let timer = DispatchSource.makeTimerSource(queue: queue)
            timer.schedule(deadline: .now() + 0.3, repeating: 0.3)
            timer.setEventHandler { [weak self] in self?.poll() }
            timer.resume()
            self.timer = timer
        }
    }

    /// Whether a change is read: the history is switched on and macOS allows the read.
    func setRecording(_ on: Bool) {
        queue.async { self.recording = on }
    }

    /// One read, made so that macOS shows its prompt and lists Vassago in System Settings.
    func ask() {
        queue.async { _ = self.pasteboard.string(forType: .string) }
    }

    /// Puts the clip back on the clipboard, then calls `done` on the main thread: false when its data is gone.
    func put(_ clip: Clip, done: @escaping (Bool) -> Void) {
        queue.async { [self] in
            guard let payload = store.payload(of: clip.id) else {
                drop(history.remove(id: clip.id).map { [$0] } ?? [])
                DispatchQueue.main.async { done(false) }
                return
            }
            let items = payload.map { types -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in types {
                    item.setData(data, forType: NSPasteboard.PasteboardType(type))
                }
                return item
            }
            // The marker keeps the watcher from recording this write, so the list keeps its order.
            items.first?.setString("1", forType: Self.own)
            pasteboard.clearContents()
            pasteboard.writeObjects(items)
            DispatchQueue.main.async { done(true) }
        }
    }

    func delete(_ clip: Clip) {
        queue.async { [self] in drop(history.remove(id: clip.id).map { [$0] } ?? []) }
    }

    func clear() {
        queue.async { [self] in drop(history.removeAll()) }
    }

    /// Presses Command+V in the app in front. macOS ignores it unless Accessibility is granted.
    static func pressPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: keyDown)
            event?.flags = .maskCommand
            event?.post(tap: .cgSessionEventTap)
        }
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != seen else { return }
        guard recording else {
            seen = count
            return
        }
        // A copying app clears the clipboard, which moves the counter, and writes a moment later
        // without moving it again. So an empty clipboard is looked at again on the next tick.
        guard let types = pasteboard.types, !types.isEmpty else { return }
        seen = count
        guard let (payload, clip, thumbnail) = read() else { return }
        // Data first and the index after, so the index never names data that is not there.
        guard store.write(payload, thumbnail: thumbnail, id: clip.id) else { return }
        drop(history.add(clip))
    }

    /// Saves the index, deletes the files of the clips that left, and tells the main thread.
    private func drop(_ gone: [Clip]) {
        store.save(history.clips)
        store.delete(gone.map(\.id))
        publish()
    }

    private func publish() {
        let clips = history.clips
        DispatchQueue.main.async { self.onChange(clips) }
    }

    /// What is on the clipboard as a clip to keep, or nil when it is to be skipped.
    private func read() -> (Payload, Clip, Data?)? {
        guard !(pasteboard.types ?? []).contains(where: { Self.skipped.contains($0.rawValue) }) else { return nil }
        var payload: Payload = []
        var files: [URL] = []
        var text: String?
        var image: Data?
        for item in pasteboard.pasteboardItems ?? [] {
            var kept: [String: Data] = [:]
            let string = item.string(forType: .string)
            let hasText = string.map { !$0.allSatisfy(\.isWhitespace) } ?? false
            if let reference = item.data(forType: .fileURL), let url = URL(dataRepresentation: reference, relativeTo: nil) {
                // Finder copies a reference by file id; the path form has the file's name.
                files.append((url as NSURL).filePathURL ?? url)
                kept[NSPasteboard.PasteboardType.fileURL.rawValue] = reference
                if hasText { kept[NSPasteboard.PasteboardType.string.rawValue] = item.data(forType: .string) }
            } else {
                if hasText {
                    for type in [.string, .rtf, .html] as [NSPasteboard.PasteboardType] {
                        kept[type.rawValue] = item.data(forType: type)
                    }
                    text = text ?? string
                }
                if let png = item.data(forType: .png) ?? item.data(forType: .tiff).flatMap(Self.converted) {
                    kept[NSPasteboard.PasteboardType.png.rawValue] = png
                    image = image ?? png
                }
            }
            if !kept.isEmpty { payload.append(kept) }
        }
        let bytes = payload.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
        guard !payload.isEmpty, bytes <= Self.largest else { return nil }

        let kind: Clip.Kind
        let title: String
        var thumbnail: Data?
        if let first = files.first {
            kind = .files
            title = files.count == 1 ? first.lastPathComponent : "\(first.lastPathComponent) and \(files.count - 1) more"
            thumbnail = Self.icon(of: first)
        } else if let text {
            // Office apps add a picture of the text they copy, so text decides before an image does.
            kind = .text
            title = VassagoEngine.title(forText: text)
        } else {
            guard let image, let source = CGImageSourceCreateWithData(image as CFData, nil),
                  let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = properties[kCGImagePropertyPixelWidth] as? Int,
                  let height = properties[kCGImagePropertyPixelHeight] as? Int else { return nil }
            kind = .image
            title = "Image \(width) × \(height)"
            // At most 128 pixels on its longer side.
            let options = [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 128] as [CFString: Any]
            thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary).flatMap(Self.encoded)
        }
        let clip = Clip(id: UUID().uuidString, kind: kind, title: title, bytes: bytes, digest: Store.digest(of: payload))
        return (payload, clip, thumbnail)
    }

    /// PNG data for an image in another format, or nil if it cannot be read.
    private static func converted(_ data: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        return CGImageSourceCreateImageAtIndex(source, 0, nil).flatMap(encoded)
    }

    private static func encoded(_ image: CGImage) -> Data? {
        let data = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        return CGImageDestinationFinalize(destination) ? data as Data : nil
    }

    /// The file's Finder icon, 64 pixels square.
    private static func icon(of file: URL) -> Data? {
        var frame = CGRect(x: 0, y: 0, width: 64, height: 64)
        return NSWorkspace.shared.icon(forFile: file.path).cgImage(forProposedRect: &frame, context: nil, hints: nil).flatMap(encoded)
    }
}
